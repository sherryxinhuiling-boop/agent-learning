# ============================================================
# 1. 变量：给一个数据起名字
# ============================================================
# Python 不需要提前声明类型，直接赋值就行。
# 等号左边是名字，右边是值。

name = "AI Agent 学习计划"
weeks = 16
hours_per_week = 25

print("=== 1. 变量与打印 ===")
print("名称：", name)
print("总周数：", weeks)


# ============================================================
# 2. f-string：把变量嵌进字符串
# ============================================================
# 字符串前面加个 f，里面的大括号 {} 就会被替换成变量的值。
# 这是 Python 里最常用的字符串写法，务必记住。

total_hours = weeks * hours_per_week          # 乘号就是 *

print("\n=== 2. f-string ===")
print(f"「{name}」共 {weeks} 周，每周 {hours_per_week} 小时，合计 {total_hours} 小时")


# ============================================================
# 3. 列表 + 循环：对一堆数据做同样的事
# ============================================================
# 列表用方括号包起来，元素之间用逗号分隔。
# for 循环会把列表里的每一项依次取出来。

stages = ["编程地基", "LLM 应用入门", "RAG 知识库", "Agent 核心", "产品化上线", "求职与作品集"]

print("\n=== 3. 列表与循环 ===")
for index, stage in enumerate(stages, start=1):
    print(f"  阶段 {index}：{stage}")

print(f"  共 {len(stages)} 个阶段")           # len() 取长度


# ============================================================
# 4. 条件判断：根据情况走不同的分支
# ============================================================
# 注意冒号和缩进 —— Python 用缩进（4 个空格）表示代码块的层级，
# 这是 Python 和其他语言最大的区别，缩进错了程序就会报错。

progress = 3

print("\n=== 4. 条件判断 ===")
if progress == 0:                             # == 是判断相等，= 是赋值
    print("  还没开始，现在就是最好的时机。")
elif progress < len(stages):
    print(f"  已完成 {progress} 个阶段，还剩 {len(stages) - progress} 个。")
else:
    print("  五个阶段全部完成。")


# ============================================================
# 5. 字典：带标签的数据
# ============================================================
# 字典用大括号，存的是「键: 值」的配对。
# 后面学 Agent 时，工具的输入输出全是这种结构，非常重要。

project = {
    "名称": "个人 CLI 助手",
    "周次": 5,
    "状态": "未开始",
}

print("\n=== 5. 字典 ===")
print(f"  下一个项目：{project['名称']}（第 {project['周次']} 周）")
project["状态"] = "进行中"                      # 修改某个键的值
print(f"  状态已更新为：{project['状态']}")


# ============================================================
# 6. 函数：把一段逻辑打包，随时复用
# ============================================================
# def 定义函数，return 把结果交出去。

def greet(who):
    """返回一句问候语。（这一行是文档字符串，说明函数干什么用）"""
    return f"你好，{who}！"


def describe_stage(index):
    """根据阶段序号，返回该阶段的描述。"""
    if index < 1 or index > len(stages):
        return "序号超出范围"
    return f"第 {index} 个阶段是「{stages[index - 1]}」"


print("\n=== 6. 函数 ===")
print(" ", greet("同学"))
print(" ", describe_stage(3))
print(" ", describe_stage(5))


# ============================================================
# 练习 4：新增变量 your_name，用 f-string 打印
